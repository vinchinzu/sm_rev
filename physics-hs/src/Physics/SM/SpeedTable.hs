-- | ROM X speed tables ($90:9F55 / $A08D / $A1DD).
--
-- One 12-byte entry per movement type: accel, max, decel as 16.16 pairs.
-- Bank 90 labels Normal at $9F55 (C's addr_kSamusSpeedTable_Normal_X + 12).
-- These are the walk / run / air numbers the residual stepper actually needs.
module Physics.SM.SpeedTable
  ( SpeedEntry (..)
  , speedEntry
  , signedMax
  ) where

import Data.Word (Word16)
import Physics.SM.Types

-- | One movement-type row of the X speed table.
data SpeedEntry = SpeedEntry
  { seAccel :: !Velocity
  , seMax   :: !Velocity
  , seDecel :: !Velocity
  } deriving stock (Eq, Show)

-- | Max speed with the same sign as the requested direction.
signedMax :: SpeedEntry -> Int -> Velocity
signedMax entry dir
  | dir < 0   = negateVelocity (seMax entry)
  | otherwise = seMax entry

-- | Select the residual-relevant speed-table row.
speedEntry :: Environment -> MovementType -> SpeedEntry
speedEntry env mt = entryFor env (unMovementType mt)

entryFor :: Environment -> Word16 -> SpeedEntry
entryFor EnvAir      = airEntry
entryFor EnvWater    = waterEntry
entryFor EnvLavaAcid = lavaEntry

-- Air table at $90:9F55. Unused movement types fall back to the run row.
airEntry :: Word16 -> SpeedEntry
airEntry 0x00 = e 0x0000 0xC000 0x0000 0x0000 0x0000 0x8000 -- standing
airEntry 0x01 = e 0x0000 0x3000 0x0002 0xC000 0x0000 0x8000 -- running
airEntry 0x02 = e 0x0000 0xC000 0x0001 0x4000 0x0000 0x8000 -- jumping
airEntry 0x03 = e 0x0000 0xC000 0x0001 0x6000 0x0000 0x8000 -- spin
airEntry 0x04 = e 0x0000 0xC000 0x0003 0x4000 0x0000 0x8000 -- morph ground
airEntry 0x05 = e 0x0000 0xC000 0x0000 0x0000 0x0000 0x8000 -- crouch
airEntry 0x06 = e 0x0000 0xC000 0x0001 0x0000 0x0000 0x8000 -- falling
airEntry 0x08 = e 0x0000 0xC000 0x0001 0x0000 0x0000 0x8000 -- morph falling
airEntry 0x10 = e 0x0000 0xC000 0x0000 0x8000 0x0000 0x8000 -- moonwalk
airEntry _    = airEntry 0x01

waterEntry :: Word16 -> SpeedEntry
waterEntry 0x00 = e 0x0000 0xC000 0x0000 0x0000 0x0000 0x0800
waterEntry 0x01 = e 0x0000 0x0400 0x0002 0xC000 0x0000 0x0800
waterEntry 0x02 = e 0x0000 0xC000 0x0001 0x4000 0x0000 0x0800
waterEntry 0x03 = e 0x0000 0xC000 0x0001 0x6000 0x0000 0x0800
waterEntry 0x04 = e 0x0000 0x0400 0x0002 0xC000 0x0000 0x0800
waterEntry 0x05 = e 0x0000 0xC000 0x0000 0x0000 0x0000 0x0800
waterEntry 0x06 = e 0x0000 0xC000 0x0001 0x0000 0x0000 0x0800
waterEntry 0x08 = e 0x0000 0x0400 0x0001 0x8000 0x0000 0x0800
waterEntry _    = waterEntry 0x01

lavaEntry :: Word16 -> SpeedEntry
lavaEntry 0x00 = e 0x0000 0xC000 0x0000 0x0000 0x0000 0x4000
lavaEntry 0x01 = e 0x0000 0x0400 0x0001 0xC000 0x0000 0x4000
lavaEntry 0x02 = e 0x0000 0xC000 0x0001 0x4000 0x0000 0x4000
lavaEntry 0x03 = e 0x0000 0xC000 0x0001 0x6000 0x0000 0x4000
lavaEntry 0x04 = e 0x0000 0x0400 0x0002 0xC000 0x0000 0x4000
lavaEntry 0x05 = e 0x0000 0xC000 0x0000 0x0000 0x0000 0x4000
lavaEntry 0x06 = e 0x0000 0xC000 0x0001 0x0000 0x0000 0x4000
lavaEntry 0x08 = e 0x0000 0x0400 0x0001 0x6000 0x0000 0x4000
lavaEntry _    = lavaEntry 0x01

e :: Word16 -> Word16 -> Word16 -> Word16 -> Word16 -> Word16 -> SpeedEntry
e ap as mp ms dp ds = SpeedEntry
  { seAccel = Velocity (fromIntegral ap) (Subpixel as)
  , seMax   = Velocity (fromIntegral mp) (Subpixel ms)
  , seDecel = Velocity (fromIntegral dp) (Subpixel ds)
  }
